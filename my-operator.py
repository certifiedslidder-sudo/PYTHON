#ARITHMETIC OPERATOR
a = 50
b =3
print("the value of",a, "+",b, "is: ", a+b)
print("the value of",a, "-",b, "is: ", a-b)
print("the value of",a, "*",b, "is: ", a*b)
print("the value of",a, "/",b, "is: ", a/b)
print("the value of",a, "//",b, "is: ", a//b)  #yields quotients after discarding fractional part.
print("the value of",a, "**",b, "is: ", a**b) #yields exponential(50*50*50)



